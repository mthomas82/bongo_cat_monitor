"""Bongo Cat sprite studio: pixel editor + 240x320 display layout.

  python3 tools/sprite_studio.py              # serve http://127.0.0.1:8765
  python3 tools/sprite_studio.py convert-all  # rebuild animations/*.c from PNGs
  python3 tools/sprite_studio.py convert PATH.png --layer face --name wink
"""

